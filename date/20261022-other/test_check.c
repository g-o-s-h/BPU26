#include <stdio.h>

int main() {
    printf("--- 验证单选题 ---\n");

    // 题 5：整数除法
    printf("题5: 10/3 = %d\n", 10 / 3);

    // 题 7：强制类型转换与默认浮点输出
    float x = 3.6;
    int i = (int)x;
    printf("题7: x=%%f 输出为 %f, i=%%d 输出为 %d\n", x, i);

    // 题 8 与 11：复合赋值优先级
    int x8 = 2, y8 = 3, z8 = 4;
    x8 *= y8 + z8; // 等价于 x8 = x8 * (y8 + z8)
    printf("题8: x8 的值 = %d (预期为 14)\n", x8);

    int i11 = 7, j11 = 8;
    i11 *= j11 + 1;
    printf("题11: i11=%d, j11=%d (预期为 63, 8)\n", i11, j11);

    // 题 12：逗号表达式
    int i12, j12, k12, x12;
    x12 = (i12 = 4, j12 = 16, k12 = 32);
    printf("题12: x12 的值 = %d (预期为 32)\n", x12);

    // 题 13：逻辑非与关系运算的优先级
    int i13 = 10, j13 = 5;
    // ! 的优先级高于 <，所以是 (!i13) < j13 即 0 < 5
    printf("题13: !i13 < j13 的输出 = %d (预期为 1)\n", !i13 < j13);

    // 题 14：字符运算
    char c2 = 'A' + '6' - '3';
    printf("题14: c2 (%%d) = %d (预期为 68)\n", c2);

    // 题 16：取模运算
    int n16 = 10, i16 = 4;
    n16 = n16 % (i16 + 1);
    printf("题16: n16 的值 = %d (预期为 0)\n", n16);

    // 题 17：值不为6的表达式
    int x17 = 2;
    // printf("%d\n", x17 *= x17 + 1); // 这会输出 6
    printf("题17: (x17 == 6) 的返回值 = %d (预期为 0)\n", x17 == 6);

    // 题 19：求余与除法优先级
    printf("题19: 17%%4/8 = %d (预期为 0)\n", 17 % 4 / 8);

    return 0;
}